const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const url = process.env.HOME_TEST_URL || 'http://127.0.0.1:4173/';
const output = '.omx/artifacts/wide-main-slider';
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 2048, height: 1100 }, reducedMotion: 'reduce' });
    const errors = [], failed = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => { if (!response.ok()) failed.push(response.url()); });
    await page.goto(url);
    const slider = page.locator('[data-main-slider]');
    await page.waitForFunction(() => document.querySelector('[data-main-slider]').dataset.ready === 'true');
    const originals = slider.locator('[data-main-slide]:not([data-main-clone])');
    assert.equal(await originals.count(), 16);
    assert.equal(await slider.locator('[data-main-clone][inert][aria-hidden="true"]').count(), 4);
    assert.equal(await originals.locator('.main-slider__image > img').count(), 16);
    assert.equal(await originals.locator('.main-slider__text > h2').count(), 16);
    assert.equal(await originals.locator('.main-slider__actions > a').count(), 16);
    await slider.locator('img').evaluateAll(async imgs => Promise.all(imgs.map(async img => { img.loading = 'eager'; await img.decode(); })));
    assert.equal(await originals.first().locator('.main-slider__image img').getAttribute('src'), 'assets/hero/kitchen/dadazzang-tableware.png');
    assert.equal(await originals.first().locator('h2').innerText(), '일본 수입 주방·생활용품\n사업자 전문 도매몰');
    assert.equal(await originals.first().locator('.main-slider__description').count(), 0);
    assert.equal(await originals.first().locator('.main-slider__brand').innerText(), 'DADAZZANG');
    const index = () => slider.getAttribute('data-slide-index');
    const measurements = [];
    for (const width of [1440, 1834, 2048]) {
      await page.setViewportSize({ width, height: 1100 });
      await page.waitForFunction(() => { const el = document.querySelector('.main-slider__slide.is-active').getBoundingClientRect(); return Math.abs(el.x + el.width / 2 - innerWidth / 2) < 1; });
      const geometry = await slider.evaluate(el => {
        const panel = el.querySelector('.is-active');
        const box = panel.getBoundingClientRect();
        const root = el.getBoundingClientRect();
        const next = panel.nextElementSibling.getBoundingClientRect();
        return { x: box.x, y: box.y - root.y, width: box.width, height: box.height, gap: next.x - box.right, radius: getComputedStyle(panel).borderRadius };
      });
      assert.ok(Math.abs(geometry.width / width - .741211) < .0001);
      assert.ok(Math.abs(geometry.width / geometry.height - 2.9533) < .001);
      assert.equal(geometry.y, 21);
      assert.equal(geometry.gap, 20);
      assert.equal(geometry.radius, '20px');
      measurements.push({ viewport: width, ...geometry });
      await slider.screenshot({ path: `${output}/slider-${width}.png` });
    }
    await slider.getByRole('button', { name: '다음 슬라이드', exact: true }).click();
    assert.equal(await index(), '1');
    await slider.getByRole('button', { name: '이전 슬라이드', exact: true }).click();
    assert.equal(await index(), '0');
    assert.equal(await page.locator('#local-notice').count(), 0, 'slider controls do not trigger the generic notice');
    await slider.focus();
    await slider.press('ArrowLeft');
    assert.equal(await index(), '15');
    await slider.press('ArrowRight');
    assert.equal(await index(), '0');
    await slider.press('End');
    assert.equal(await index(), '15');
    await slider.press('Home');
    assert.equal(await index(), '0');
    for (let i = 0; i < 16; i++) {
      const slide = originals.nth(i);
      assert.equal(await slide.getAttribute('inert'), null);
      const layout = await slide.evaluate(el => {
        const text = el.querySelector('.main-slider__text').getBoundingClientRect();
        const actions = el.querySelector('.main-slider__actions').getBoundingClientRect();
        const image = el.querySelector('.main-slider__image').getBoundingClientRect();
        const box = el.getBoundingClientRect();
        return { separated: actions.top > text.bottom, textFits: text.right < box.right && text.top >= box.top && actions.bottom < box.bottom, imageFits: Math.abs(image.right - box.right) < 1 && image.height === box.height };
      });
      assert.ok(layout.separated && layout.textFits && layout.imageFits, `slide ${i + 1} regions fit independently`);
      await slider.press('ArrowRight');
    }
    assert.equal(await index(), '0');
    const cta = originals.first().locator('.main-slider__button');
    await cta.focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await index(), '1');
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'SHIMOMURA 자세히 보기');
    await slider.press('Home');
    const viewport = await slider.locator('.main-slider__viewport').boundingBox();
    await page.mouse.move(1300, viewport.y + 170);
    await page.mouse.down();
    await page.mouse.move(1100, viewport.y + 175, { steps: 8 });
    await page.mouse.up();
    assert.equal(await index(), '1');
    await fs.writeFile(`${output}/measurements.json`, JSON.stringify(measurements, null, 2));

    const motion = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    motion.on('pageerror', error => errors.push(error.message));
    await motion.goto(url);
    const moving = motion.locator('[data-main-slider]');
    await motion.waitForFunction(() => document.querySelector('[data-main-slider]').dataset.slideIndex === '1', null, { timeout: 7500 });
    await motion.waitForFunction(() => !document.querySelector('[data-main-slider]').classList.contains('is-resetting'));
    await moving.hover();
    await motion.waitForTimeout(5300);
    assert.equal(await moving.getAttribute('data-slide-index'), '1', 'hover pauses automatic playback');
    await moving.getByRole('button', { name: '슬라이드 자동재생 일시정지', exact: true }).click();
    assert.equal(await moving.locator('[data-main-toggle]').getAttribute('aria-pressed'), 'true');
    await moving.press('End');
    await motion.waitForTimeout(750);
    await moving.press('ArrowRight');
    await motion.waitForTimeout(750);
    assert.equal(await moving.getAttribute('data-slide-index'), '0');
    assert.equal(await moving.locator('.is-active[data-main-clone]').count(), 0);
    await moving.press('ArrowLeft');
    await motion.waitForTimeout(750);
    assert.equal(await moving.getAttribute('data-slide-index'), '15');
    assert.equal(await moving.locator('.is-active[data-main-clone]').count(), 0);
    await moving.getByRole('button', { name: '슬라이드 자동재생 시작', exact: true }).click();
    await motion.emulateMedia({ reducedMotion: 'reduce' });
    await motion.mouse.move(5, 1000);
    await motion.evaluate(() => document.activeElement.blur());
    assert.equal(await moving.getAttribute('data-autoplay'), 'paused');
    assert.deepEqual(errors, []);
    assert.deepEqual(failed, []);
    console.log('PASS: reference geometry at 1440/1834/2048px; 16 independent image/text/CTA regions; arrows, keyboard/focus, swipe, loop boundaries, autoplay, pause and reduced motion; no errors.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
